    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);
    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);

    // 初始亮度設定 (佔空比 0~100 對應 ARR 0~10000)
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, light_level * 100);
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, water_level * 100);

