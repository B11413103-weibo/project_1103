// TIM 定時器中斷回呼函式
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM2)
    {
        static uint16_t water_tick = 0;
        static uint16_t report_tick = 0;
        static uint16_t blink_tick = 0;

        // 每 100 毫秒扣水 1%
        if (++water_tick >= 100)
        {
            water_tick = 0;
            if (water_level > 0)
            {
                water_level--;
                __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, water_level * 100);
            }
        }

        // 每 1000 毫秒設定回報旗標
        if (++report_tick >= 1000)
        {
            report_tick = 0;
            uart_tx_flag = 1;
        }

        // 每 50 毫秒處理警報燈閃爍 (10Hz)
        if (++blink_tick >= 50)
        {
            blink_tick = 0;
            if (water_level < 20) {
                HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_5);
            } else {
                HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET);
            }
        }
    }
}

// EXTI 外部中斷回呼函式 (按鍵)
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
    if (GPIO_Pin == GPIO_PIN_13)
    {
        uint32_t current_tick = HAL_GetTick();

        // 50ms 去彈跳
        if (current_tick - last_button_tick > 50)
        {
            if (water_level < 20) {
                water_level = 100;
            } else {
                water_level = 0;
            }

            // 立即更新 PWM
            __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, water_level * 100);
            last_button_tick = current_tick;
        }
    }
}
